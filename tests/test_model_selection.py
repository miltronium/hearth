    assert blocked.status_code == 503
    assert blocked.json()["status"] == "loading"
    assert fake.loads == []
    fake.load_gate.set()
    ready = _wait_ready(client, "ready")
    assert ready.status_code == 200
    assert fake.loaded_paths() == [weights(CODER7)]  # the default's weights, really read


