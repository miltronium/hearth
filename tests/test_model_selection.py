# -- eviction under the RAM ceiling --------------------------------------------------------


def test_lru_eviction_drops_the_weights_and_a_return_reloads_them(fake, tmp_path, monkeypatch):
    unload_threads: list[str] = []
    real_unload = MLXProvider._unload_here

    def spy(self):
        unload_threads.append(threading.current_thread().name)
        real_unload(self)

    monkeypatch.setattr(MLXProvider, "_unload_here", spy)
    pool = mlx_pool(_settings(tmp_path, ram_ceiling_gb=6.0))  # 4.5 + 2.0 > 6.0
    req = lambda m: GenRequest(messages=[Message(role="user", content="x")], model=m)  # noqa: E731

    assert pool.generate(req(CODER7)).text == tag(CODER7)
    coder = pool.manager.peek(CODER7)
    assert coder.is_loaded
    assert pool.generate(req(SMALL)).text == tag(SMALL)
    assert pool.manager.resident_ids() == [SMALL]
    assert pool.manager.resident_ram_gb() <= 6.0
    assert coder.is_loaded is False  # its weights were actually dropped, not just forgotten
    assert unload_threads and all(t.startswith("hearth-mlx") for t in unload_threads)
    assert pool.generate(req(CODER7)).text == tag(CODER7)
    assert fake.loaded_paths() == [weights(CODER7), weights(SMALL), weights(CODER7)]


_CHURN_CHILD = "HEARTH_TEST_CHURN_CHILD"
_CHURN_TIMEOUT_S = 60


def test_concurrent_churn_never_holds_weights_outside_the_ceiling(fake, tmp_path):
    """Pick-a-model and generate are one MLX job, so eviction cannot land between them.

    If the residency lookup ran on the request thread and only generation hopped to the MLX
    thread, an eviction could run in the gap and the generation would quietly reload the
    evicted weights outside the manager's accounting — RAM over the ceiling with every
    counter saying otherwise. Asserted two ways: every residency decision ran on the MLX
    thread, and at the end no provider holds weights the manager does not count.

    That mutant can also DEADLOCK (a request thread holds the manager's load lock while
    waiting on an MLX-thread unload; the MLX thread waits for the load lock). The MLX thread
    is process-global and non-daemon, so a thread + join(timeout) here would report the
    failure and then hang the next MLX test and interpreter exit. The body therefore runs
    in a child pytest with a hard timeout: a deadlock is a clean, attributed FAIL.
    """
    if os.environ.get(_CHURN_CHILD) != "1":
        node = f"{Path(__file__).resolve()}::{sys._getframe().f_code.co_name}"
        try:
            child = subprocess.run(
                [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", node],
                env={**os.environ, _CHURN_CHILD: "1"},
                capture_output=True, text=True, timeout=_CHURN_TIMEOUT_S,
            )
        except subprocess.TimeoutExpired:
            pytest.fail(
                f"concurrent churn did not finish in {_CHURN_TIMEOUT_S}s — deadlock between "
                "the manager's load lock and the MLX thread"
            )
        assert child.returncode == 0 and "1 passed" in child.stdout, (
            child.stdout[-3000:] + child.stderr[-2000:]
        )
        return
    pool = mlx_pool(_settings(tmp_path, ram_ceiling_gb=6.0))  # only one of 7B/3B fits
    made: list[MLXProvider] = []
    real_factory = pool._factory

    def factory(model_id, ram_gb):
        made.append(real_factory(model_id, ram_gb))
        return made[-1]

    pool._factory = factory
    get_threads: list[str] = []
    real_get = pool.manager.get

    def spy_get(model_id):
        get_threads.append(threading.current_thread().name)
        return real_get(model_id)

    pool.manager.get = spy_get
    models = [CODER7 if i % 2 else SMALL for i in range(24)]

    def run(m):
        req = GenRequest(messages=[Message(role="user", content="x")], model=m)
        if m == SMALL:
            return m, "".join(d.text for d in pool.stream_deltas(req))
        return m, pool.generate(req).text

    with ThreadPoolExecutor(max_workers=8) as ex:
        for m, text in ex.map(run, models):
            assert text == tag(m)
    assert get_threads and all(t.startswith("hearth-mlx") for t in get_threads)
    resident = {id(p) for p in (r.provider for r in pool.manager.residents())}
    holding = [p.model_id for p in made if p.is_loaded and id(p) not in resident]
    assert holding == [], f"weights held outside the manager's accounting: {holding}"
    assert pool.manager.resident_ram_gb() <= 6.0


