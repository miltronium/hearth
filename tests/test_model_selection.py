def test_concurrent_mixed_requests_each_get_their_own_weights(fake, tmp_path, local_policy):
    """3B and 7B, streaming and not, from many request threads at once."""
    app, _, _ = _app(tmp_path, local_policy)
    client = TestClient(app)
    jobs = [(SMALL if i % 2 else CODER7, bool(i % 3 == 0)) for i in range(16)]

    def run(job):
        model, stream = job
        if stream:
            text, final = _stream_text_and_final(_chat(client, model, f"q{model}", stream=True))
            return model, text, final["hearth"]["model"]
        body = _chat(client, model, f"q{model}").json()
        return model, body["choices"][0]["message"]["content"], body["hearth"]["model"]

    with ThreadPoolExecutor(max_workers=8) as pool:
        results = list(pool.map(run, jobs))
    for model, text, reported in results:
        assert text == tag(model)
        assert reported == model
    # Every load and every generation ran on the one MLX thread (thread-local GPU stream).
    threads = {t for _, t in fake.loads} | {t for _, t in fake.generations}
    assert len(threads) == 1 and next(iter(threads)).startswith("hearth-mlx")
    assert len(fake.generations) == len(jobs)


def test_streaming_telemetry_comes_from_the_provider_that_ran(tmp_path, local_policy):
    """A provider that answers with other weights is reported as such, not as the request.

    Before, the final SSE chunk and the RequestRecord carried ``decision.model`` — the model
    that was ASKED for — so a stream served by the wrong weights still reported the right
    name. A provider that ignores the requested id exposes exactly that.
    """

    class StubbornProvider:
        name = "stubborn"

        def capabilities(self):
            return None

        def generate(self, req):
            raise AssertionError("streaming test")

        def stream(self, req):
            yield "x"

        def stream_deltas(self, req):
            yield StreamDelta(text="answer")
            yield StreamDelta(finish_reason="stop", model="the-weights-that-actually-ran")

        def footprint(self, model_id):
            return None

    provider = StubbornProvider()
    router = _router(provider, local_policy)
    settings = Settings(backend="echo", home=tmp_path / "h", require_auth=False, warmup=False)
    client = TestClient(create_app(provider=provider, settings=settings, router=router))
    _, final = _stream_text_and_final(_chat(client, SMALL, stream=True))
    assert final["hearth"]["model"] == "the-weights-that-actually-ran"
    assert _records(router)[-1].model == "the-weights-that-actually-ran"


