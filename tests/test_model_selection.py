# -- /ready is 503 until weights are loaded, and when the load fails -----------------------


def _wait_ready(client, want_status: str, timeout=5.0):
    deadline = time.monotonic() + timeout
    while True:
        resp = client.get("/v1/hearth/admin/ready")
        if resp.json()["status"] == want_status or time.monotonic() > deadline:
            return resp
        time.sleep(0.02)


def test_ready_is_503_until_the_weights_are_loaded(fake, tmp_path, local_policy):
    fake.load_gate = threading.Event()
    app, _, _ = _app(tmp_path, local_policy, warmup=True)
    client = TestClient(app)
