"""The model a request names is the model that generates it (and /ready tells the truth).

Before this, ``MLXProvider`` served ``self.model_id`` whatever ``GenRequest.model`` said and
the gateway's ``ModelManager`` factory returned the SAME provider for every id. So the /chat
dropdown, the ``model`` field of ``/v1/chat/completions`` and ``/v1/hearth/agent``, and every
per-class rung of ``config/routing.finance.yaml`` were generated by the default model — and
``/v1/hearth/admin/ready`` said 200 with no weights loaded at all.

These tests assert on the OUTCOME (CLAUDE.md §3), never on what a response says about
itself: the fake ``mlx_lm`` below records the exact path every ``load()`` read and tags every
generated token with the weights that produced it, so "generated BY X" is a property of the
text, not of a telemetry field that could be filled in from the request.
"""

