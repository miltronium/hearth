def weights(model_id: str) -> str:
    """The on-disk path the fake resolver hands mlx_lm.load for ``model_id``."""
    return f"/weights/{model_id}"


def tag(model_id: str) -> str:
    """The marker every token generated by ``model_id``'s weights carries."""
    return f"<<{weights(model_id)}>>"


# -- a fake mlx_lm that cannot lie about which weights ran ---------------------------------


class _Tokenizer:
    eos_token = "<|im_end|>"

    def encode(self, text):
        return list(text)

    def apply_chat_template(self, chat, tokenize, add_generation_prompt):
        return chat[-1]["content"]


class _Weights:
    def __init__(self, path: str) -> None:
        self.path = path


class _Response:
    def __init__(self, text: str, finish_reason: str | None = None) -> None:
        self.text = text
        self.finish_reason = finish_reason


class FakeMLX:
    """``load`` records the path it read; ``stream_generate`` tags output with that path."""

    def __init__(self) -> None:
        self.loads: list[tuple[str, str]] = []  # (path, thread name)
        self.generations: list[tuple[str, str]] = []
        self.missing: set[str] = set()
        self.load_gate: threading.Event | None = None
        self.reply = lambda path, prompt: f"<<{path}>>"

    def load(self, path, **kwargs):
        if self.load_gate is not None:
            assert self.load_gate.wait(10), "test never released the load"
        self.loads.append((path, threading.current_thread().name))
        return _Weights(path), _Tokenizer()

    def stream_generate(self, model, tokenizer, prompt, max_tokens):
        self.generations.append((model.path, threading.current_thread().name))
        text = self.reply(model.path, prompt)
        half = max(1, len(text) // 2)
        yield _Response(text[:half])
        yield _Response(text[half:], "stop")

    def resolve(self, model_id, allow_downloads=None):
        if model_id in self.missing:
            raise ModelNotOnDiskError(f"model {model_id!r} is not on disk")
        return weights(model_id)

    def loaded_paths(self) -> list[str]:
        return [p for p, _ in self.loads]

    def generated_paths(self) -> list[str]:
        return [p for p, _ in self.generations]


@pytest.fixture
def fake(monkeypatch) -> FakeMLX:
    fake = FakeMLX()
    module = types.ModuleType("mlx_lm")
    module.load = fake.load
    module.stream_generate = lambda *a, **k: fake.stream_generate(*a, **k)
    module.__spec__ = importlib.machinery.ModuleSpec("mlx_lm", loader=None)
    monkeypatch.setitem(sys.modules, "mlx_lm", module)
    monkeypatch.setattr(mlx_mod, "resolve_local_model", fake.resolve)
    # The readiness disk probe: the fake's paths are not real directories, so its "on disk"
    # is the fake resolver's answer (the real probe's exists-check is tested on its own).
    monkeypatch.setattr(providers_pkg, "_locate_on_disk", fake.resolve)
    monkeypatch.delenv("HEARTH_DEFAULT_MODEL", raising=False)
    monkeypatch.delenv("HEARTH_ROUTING_YAML", raising=False)
    return fake


def _settings(tmp_path, **kw) -> Settings:
    base = dict(
        backend="mlx", home=tmp_path / ".hearth", require_auth=False, warmup=False,
        ram_ceiling_gb=24.0,
    )
    base.update(kw)
    return Settings(**base)


def _router(provider, policy) -> Router:
    return Router(
        local_provider=provider,
        policy=policy,
        budget=BudgetAccountant(policy.defaults.remote_budget_tokens_per_day),
        metrics=MetricsStore(),
    )


def _app(tmp_path, policy, **kw):
    settings = _settings(tmp_path, **kw)
    pool = mlx_pool(settings)
    router = _router(pool, policy)
    return create_app(provider=pool, settings=settings, router=router), pool, router


def _records(router):
    return list(router.metrics._records)  # MetricsStore has no public listing


def _chat(client, model, text="hello", stream=False, **extra):
    body = {"model": model, "messages": [{"role": "user", "content": text}], "stream": stream}
    body.update(extra)
    return client.post("/v1/chat/completions", json=body)


def _sse_events(resp) -> list:
    out = []
    for line in resp.text.splitlines():
        if line.startswith("data: "):
            payload = line[len("data: "):]
            out.append(payload if payload == "[DONE]" else json.loads(payload))
    return out


def _stream_text_and_final(resp):
    events = [e for e in _sse_events(resp) if e != "[DONE]"]
    text = "".join(
        (c["choices"][0]["delta"].get("content") or "") for c in events if "choices" in c
    )
    final = next(e for e in reversed(events) if e.get("hearth"))
    return text, final


