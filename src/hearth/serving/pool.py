"""One provider per model id, so the model a request names is the model that answers.

:class:`~hearth.providers.mlx.MLXProvider` holds exactly one model's weights. Before this
module the gateway's :class:`~hearth.serving.ModelManager` factory returned *the same*
provider for every id, so the /chat model dropdown, the ``model`` field of
``/v1/chat/completions`` and ``/v1/hearth/agent``, and every per-class ``local_model`` rung of
a routing ladder were all generated by the default model — while the streaming telemetry
reported the model that had been *asked for*. The check (what the request named) and the
checked thing (which weights ran) were different objects: ``CLAUDE.md`` §3.

:class:`ModelPool` is the local provider the router sees. It

* validates every id against the model registry (``config/models.yaml``): an unknown id, a
  non-chat entry, or an entry for another backend raises :class:`UnknownModelError` — never a
  silent fallback to the default. ``"auto"``/empty resolve to the registry default (the router
  has already applied the per-class ladder by the time a request arrives here);
* keeps one provider per model id — and one per (model, LoRA adapter) variant, each a full
  base reload sized at the model's ``ram_gb`` (B-069) — resident in a
  :class:`~hearth.serving.ModelManager`, LRU under ``settings.ram_ceiling_gb``;
* runs residency lookup, loading, eviction *and* generation inside a single job on the
  process's one MLX thread (``providers/mlx.py``). Because that thread runs one job at a
  time, a model cannot be evicted between being picked for a request and generating it — and
  MLX's thread-local GPU stream sees every load and every generation on the same thread.

Telemetry never comes from here: :class:`~hearth.providers.base.GenResult.model` and the
terminal :class:`~hearth.providers.base.StreamDelta.model` are filled in by the provider
instance that generated.
"""

